# SCHEMA — 5 tables (Phase A populates ppc_search_terms; the rest are scaffolded
# now so Phases B/C don't need a schema rework). All carry account_id; a `channel`
# column is reserved for future multi-channel.
# ─────────────────────────────────────────────────────────────────────────────

def _column_exists(conn, table, col):
    """True if `col` is present on `table`, on either backend (used for additive,
    idempotent migrations without a bare ALTER that would abort a PG transaction)."""
    if db.is_postgres():
        row = conn.execute(
            "SELECT 1 FROM information_schema.columns WHERE table_name=? AND column_name=?",
            (table, col)).fetchone()
        return row is not None
    rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
    return any((r["name"] if not isinstance(r, (tuple, list)) else r[1]) == col for r in rows)


def init_ppc_schema(db_path=DB_PATH):
    conn = get_db(db_path)
    pg = db.is_postgres()
    MONEY = "NUMERIC(14,4)" if pg else "REAL"
    IDCOL = ("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
             if pg else "INTEGER PRIMARY KEY AUTOINCREMENT")

    # ppc_search_terms DDL is shared between fresh-create and the target-grain rebuild
    # migration (below), so the two never drift. The PK carries target_id so a search
    # term that matches more than one target in the same hour/ad-group can't collide
    # (that collision would silently drop a target's clicks and corrupt the rules).
    ST_DDL = f"""
        CREATE TABLE IF NOT EXISTS ppc_search_terms (
            account_id        TEXT NOT NULL,
            channel           TEXT NOT NULL DEFAULT 'amazon',
            ads_account_id    TEXT,
            portfolio_id      TEXT,
            portfolio_name    TEXT,
            campaign_id       TEXT NOT NULL,
            campaign_name     TEXT,
            ad_group_id       TEXT NOT NULL,
            ad_group_name     TEXT,
            search_term       TEXT NOT NULL,
            targeting_type    TEXT,            -- 'keyword' | 'product' (ASIN) | 'other'
            advertised_sku    TEXT NOT NULL DEFAULT '',
            target_id         TEXT NOT NULL DEFAULT '',   -- Ads 'Target ID' (keyword/target/auto-expression)
            target_bid        {MONEY},                    -- current 'Target bid'
            target_type       TEXT,                       -- report 'Target type' (e.g. rsf)
            match_type_raw    TEXT,                       -- 'Targeting match type': EXACT/BROAD/PHRASE (manual)
                                                          --   | TARGETING_EXPRESSION_PREDEFINED (auto) | TARGETING_EXPRESSION
            advertised_product_id TEXT,                   -- 'Advertised product ID' (ASIN)
            date              TEXT NOT NULL,   -- YYYY-MM-DD
            hour              INTEGER NOT NULL DEFAULT -1,   -- 0..23, -1 = day-level row
            day_of_week       TEXT,
            week              INTEGER,
            impressions       INTEGER NOT NULL DEFAULT 0,
            clicks            INTEGER NOT NULL DEFAULT 0,
            spend             {MONEY} NOT NULL DEFAULT 0,
            orders            INTEGER NOT NULL DEFAULT 0,
            sales             {MONEY} NOT NULL DEFAULT 0,
            units             INTEGER NOT NULL DEFAULT 0,
            sales_promoted    {MONEY} NOT NULL DEFAULT 0,
            sales_halo        {MONEY} NOT NULL DEFAULT 0,
            imported_at       TEXT NOT NULL,
            PRIMARY KEY (account_id, campaign_id, ad_group_id, target_id, search_term, advertised_sku, date, hour)
        )
        """

    stmts = [
        ST_DDL,
        # manual-campaign keywords with current bid (Phase B bid moves apply here only)
        f"""
        CREATE TABLE IF NOT EXISTS ppc_keywords (
            account_id     TEXT NOT NULL,
            campaign_id    TEXT NOT NULL,
            ad_group_id    TEXT NOT NULL,
            keyword        TEXT NOT NULL,
            match_type     TEXT,              -- broad | phrase | exact | product
            current_bid    {MONEY},
            updated_at     TEXT,
            PRIMARY KEY (account_id, campaign_id, ad_group_id, keyword, match_type)
        )
        """,
        # every term ever harvested — the harvest-tracking dedup
        f"""
        CREATE TABLE IF NOT EXISTS ppc_harvest_log (
            id             {IDCOL},
            account_id     TEXT NOT NULL,
            source_campaign TEXT,
            term           TEXT NOT NULL,
            target_campaign TEXT,
            harvested_at   TEXT NOT NULL
        )
        """,
        # every negative ever added — powers the negative-conflict guard
        f"""
        CREATE TABLE IF NOT EXISTS ppc_negative_log (
            id             {IDCOL},
            account_id     TEXT NOT NULL,
            campaign_id    TEXT NOT NULL,
            term_or_asin   TEXT NOT NULL,
            match_type     TEXT,              -- phrase | exact | product
            added_at       TEXT NOT NULL
        )
        """,
        # the worklist (populated once rules are set)
        f"""
        CREATE TABLE IF NOT EXISTS ppc_recommendations (
            id             {IDCOL},
            account_id     TEXT NOT NULL,
            rec_type       TEXT NOT NULL,     -- pause|harvest|negative|bid_up|bid_down|manual_review
            target         TEXT,
            rationale      TEXT,
            evidence_json  TEXT,
            status         TEXT NOT NULL DEFAULT 'pending',  -- pending|approved|rejected|executed
            decided_by     TEXT,
            decided_at     TEXT,
            created_at     TEXT NOT NULL
        )
        """,
        # Phase C — per-campaign day-parting schedule. active=1 means the hourly
        # scheduler manages this campaign's on/off. The simple daily ON window is
        # [on_start_hour, on_end_hour); hour_mask (24 chars of '1'/'0') is the
        # optional per-hour override that takes precedence when set (Phase: later).
        f"""
        CREATE TABLE IF NOT EXISTS ppc_campaign_schedule (
            account_id        TEXT NOT NULL,
            campaign_id       TEXT NOT NULL,
            campaign_name     TEXT,
            active            INTEGER NOT NULL DEFAULT 0,
            on_start_hour     INTEGER NOT NULL DEFAULT 0,
            on_end_hour       INTEGER NOT NULL DEFAULT 24,
            hour_mask         TEXT,
            last_desired_state TEXT,
            last_synced_at    TEXT,
            updated_at        TEXT,
            PRIMARY KEY (account_id, campaign_id)
        )
        """,
        # every enable/pause the scheduler (or a manual test) attempts, logged.
        f"""
        CREATE TABLE IF NOT EXISTS ppc_action_log (
            id             {IDCOL},
            account_id     TEXT NOT NULL,
            campaign_id    TEXT,
            campaign_name  TEXT,
            action         TEXT,              -- 'enable' | 'pause'
            desired_state  TEXT,              -- 'enabled' | 'paused'
            result         TEXT,              -- 'ok' | 'error' | 'dry_run' | 'noop'
            detail         TEXT,
            at             TEXT NOT NULL
        )
        """,
    ]
    for s in stmts:
        conn.execute(s)
    # additive migration: temporary-pause ("snooze until") timestamp on a campaign
    # schedule. When set and in the future, the reconciler forces the campaign paused
    # regardless of its day-parting window, then clears it on expiry (auto-resume).
    # Existence-checked (not a bare ALTER) so a duplicate doesn't poison the PG txn.
    if not _column_exists(conn, "ppc_campaign_schedule", "paused_until"):
        conn.execute("ALTER TABLE ppc_campaign_schedule ADD COLUMN paused_until TEXT")
    # target-grain migration: older ppc_search_terms had no target_id (and thus a PK
    # that could collide two targets in one hour). Rebuild it to the shared ST_DDL,
    # carrying old rows over with empty target/bid fields. Only runs once.
    if not _column_exists(conn, "ppc_search_terms", "target_id"):
        conn.execute("ALTER TABLE ppc_search_terms RENAME TO ppc_search_terms_old")
        conn.execute(ST_DDL)
        conn.execute("""
            INSERT INTO ppc_search_terms
                (account_id, channel, ads_account_id, portfolio_id, portfolio_name,
                 campaign_id, campaign_name, ad_group_id, ad_group_name, search_term,
                 targeting_type, advertised_sku, target_id, target_bid, target_type,
                 match_type_raw, advertised_product_id, date, hour, day_of_week, week,
                 impressions, clicks, spend, orders, sales, units, sales_promoted,
                 sales_halo, imported_at)
            SELECT account_id, channel, ads_account_id, portfolio_id, portfolio_name,
                   campaign_id, campaign_name, ad_group_id, ad_group_name, search_term,
                   targeting_type, advertised_sku, '', NULL, NULL,
                   NULL, NULL, date, hour, day_of_week, week,
                   impressions, clicks, spend, orders, sales, units, sales_promoted,
                   sales_halo, imported_at
            FROM ppc_search_terms_old
        """)
        conn.execute("DROP TABLE ppc_search_terms_old")
        log.info("ppc_search_terms rebuilt at target grain (target_id added to PK).")
    # helpful indexes for the dashboard aggregations
    for idx in [
        "CREATE INDEX IF NOT EXISTS idx_ppc_st_acct_date ON ppc_search_terms(account_id, date)",
        "CREATE INDEX IF NOT EXISTS idx_ppc_st_campaign ON ppc_search_terms(account_id, campaign_id)",
        "CREATE INDEX IF NOT EXISTS idx_ppc_st_term ON ppc_search_terms(account_id, search_term)",
    ]:
        conn.execute(idx)
    conn.commit()
    conn.close()
    log.info("Module 3 (PPC) schema initialised.")


