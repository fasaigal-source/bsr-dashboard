def _acct_where(account_id):
    if account_id and account_id != "all":
        return " WHERE account_id=?", [account_id]
    return "", []


def _filters(account_id=None, campaign_id=None, search_term=None):
    """Build a WHERE clause for the drill-downs: account + optional campaign +
    optional search term."""
    clauses, params = [], []
    if account_id and account_id != "all":
        clauses.append("account_id=?"); params.append(account_id)
    if campaign_id:
        clauses.append("campaign_id=?"); params.append(campaign_id)
    if search_term:
        clauses.append("search_term=?"); params.append(search_term)
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    return where, params


def get_totals(account_id="all", db_path=DB_PATH):
    conn = get_db(db_path)
    w, p = _acct_where(account_id)
    row = conn.execute(f"""
        SELECT COUNT(*) AS rows, COUNT(DISTINCT search_term) AS terms,
               COUNT(DISTINCT campaign_id) AS campaigns,
               SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders,
               ROUND(SUM(sales),2) AS sales, MIN(date) AS date_min, MAX(date) AS date_max
        FROM ppc_search_terms{w}
    """, p).fetchone()
    conn.close()
    return dict(row) if row else {}


def by_day(account_id="all", campaign_id=None, search_term=None, db_path=DB_PATH):
    conn = get_db(db_path)
    w, p = _filters(account_id, campaign_id, search_term)
    rows = conn.execute(f"""
        SELECT date, SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales
        FROM ppc_search_terms{w}
        GROUP BY date ORDER BY date
    """, p).fetchall()
    conn.close()
    return [dict(r) for r in rows]


def by_hour(account_id="all", campaign_id=None, search_term=None, db_path=DB_PATH):
    """Hour-of-day breakdown (0..23). This is the day-parting view: where does
    spend convert vs waste, by time of day, optionally for one campaign or term."""
    conn = get_db(db_path)
    w, p = _filters(account_id, campaign_id, search_term)
    extra = (" AND hour >= 0") if w else (" WHERE hour >= 0")
    rows = conn.execute(f"""
        SELECT hour, SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales
        FROM ppc_search_terms{w}{extra}
        GROUP BY hour ORDER BY hour
    """, p).fetchall()
    conn.close()
    return [dict(r) for r in rows]


def entity_totals(account_id="all", campaign_id=None, search_term=None, db_path=DB_PATH):
    conn = get_db(db_path)
    w, p = _filters(account_id, campaign_id, search_term)
    row = conn.execute(f"""
        SELECT COUNT(DISTINCT search_term) AS terms, COUNT(DISTINCT campaign_id) AS campaigns,
               MAX(campaign_name) AS campaign_name,
               SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales,
               MIN(date) AS date_min, MAX(date) AS date_max
        FROM ppc_search_terms{w}
    """, p).fetchone()
    conn.close()
    return dict(row) if row else {}


def terms_for_campaign(account_id, campaign_id, limit=500, db_path=DB_PATH):
    conn = get_db(db_path)
    w, p = _filters(account_id, campaign_id)
    rows = conn.execute(f"""
        SELECT search_term, targeting_type, SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales
        FROM ppc_search_terms{w}
        GROUP BY search_term, targeting_type
        ORDER BY SUM(spend) DESC LIMIT {int(limit)}
    """, p).fetchall()
    conn.close()
    return [dict(r) for r in rows]


def campaigns_for_term(account_id, search_term, db_path=DB_PATH):
    conn = get_db(db_path)
    w, p = _filters(account_id, search_term=search_term)
    rows = conn.execute(f"""
        SELECT campaign_id, campaign_name, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales
        FROM ppc_search_terms{w}
        GROUP BY campaign_id, campaign_name
        ORDER BY SUM(spend) DESC
    """, p).fetchall()
    conn.close()
    return [dict(r) for r in rows]


# ─────────────────────────────────────────────────────────────────────────────
# TACOS — ad spend ÷ settlement-anchored total revenue (Module 2). Account-level
# headline + per-ASIN. NOT per-search-term (TACOS is undefined at term grain —
# the search-term table keeps ACOS). Two clocks: ad spend is click-date, revenue
# is settlement-date. Gated on sync freshness so it isn't divided into frozen revenue.
# ─────────────────────────────────────────────────────────────────────────────

def get_tacos(account_id="all", db_path=DB_PATH):
    import pl_ads
    conn = get_db(db_path)
    try:
        row = conn.execute("SELECT MAX(latest_synced) AS m FROM pl_sync_state").fetchone()
        last_synced = row["m"] if row and row["m"] else None
    except Exception:
        last_synced = None
    conn.close()

    cov_min, cov_max = pl_ads.get_ad_data_coverage(account_id=account_id, db_path=db_path)
    if not cov_min:
        return {"has_ad": False}

    ad_by_asin = pl_ads.get_ad_spend_by_asin(account_id, cov_min, cov_max, db_path=db_path)
    total_spend = round(sum((v.get("spend") or 0) for v in ad_by_asin.values()), 2)

    import html as _html
    conn = get_db(db_path)
    acc = " AND account_id=?" if (account_id and account_id != "all") else ""
    ap = [account_id] if acc else []
    # total settled gross (ex-VAT) over the ad-coverage window — the TACOS denominator
    total_rev = conn.execute(
        f"SELECT ROUND(SUM(sale_price_exvat),2) AS r FROM pl_line_items "
        f"WHERE substr(posted_date,1,10) >= ? AND substr(posted_date,1,10) <= ?{acc}",
        (cov_min, cov_max, *ap)).fetchone()["r"] or 0.0

    # Build SKU/canonical -> ASIN maps, normalised for two real-data quirks so the
    # per-ASIN revenue join actually hits: (1) pl_line_items.sku stores HTML
    # entities (e.g. 18&quot;X4) while the maps hold the decoded form (18"X4);
    # (2) separators/aliases differ (BD-6372=P4 vs BD-6372-P4). We match on the
    # clean canonical_sku first (alias-resolved), then fall back to a
    # HTML-unescaped raw-sku match. Both mapping sources are used: your
    # SKU→ASIN table (cogs_sku_asin) and Amazon's own advertised (asin, sku) pairs.
    alias_map = {r["variant_sku"]: r["canonical_sku"]
                 for r in conn.execute("SELECT variant_sku, canonical_sku FROM cogs_aliases").fetchall()}

    def _canon(s):
        s = s or ""
        if s in alias_map:
            return alias_map[s]
        u = _html.unescape(s)
        return alias_map.get(u, u)

    canon_to_asin, sku_to_asin = {}, {}
    for r in conn.execute("SELECT variant_sku, asin FROM cogs_sku_asin").fetchall():
        canon_to_asin.setdefault(_canon(r["variant_sku"]), r["asin"])
        sku_to_asin.setdefault(_html.unescape(r["variant_sku"] or ""), r["asin"])
    for r in conn.execute("SELECT DISTINCT asin, sku FROM ad_spend WHERE sku IS NOT NULL AND sku!=''").fetchall():
        canon_to_asin.setdefault(_canon(r["sku"]), r["asin"])
        sku_to_asin.setdefault(_html.unescape(r["sku"] or ""), r["asin"])

    rev_by_asin = {}
    for r in conn.execute(
            f"""SELECT canonical_sku, sku, SUM(sale_price_exvat) AS rev FROM pl_line_items
                WHERE substr(posted_date,1,10) >= ? AND substr(posted_date,1,10) <= ?{acc}
                GROUP BY canonical_sku, sku""", (cov_min, cov_max, *ap)).fetchall():
        a = canon_to_asin.get(r["canonical_sku"]) or sku_to_asin.get(_html.unescape(r["sku"] or ""))
        if a:
            rev_by_asin[a] = rev_by_asin.get(a, 0.0) + (r["rev"] or 0.0)
    conn.close()

    per_asin = []
    for asin, v in ad_by_asin.items():
        rev = rev_by_asin.get(asin, 0.0)
        spend = round(v.get("spend") or 0, 2)
        per_asin.append({
            "asin": asin, "spend": spend, "ad_sales": round(v.get("ad_sales") or 0, 2),
            "revenue": rev, "tacos": (spend / rev) if rev else None})
    per_asin.sort(key=lambda x: -(x["spend"] or 0))

    account_tacos = (total_spend / total_rev) if total_rev else None
    # stale = revenue hasn't caught up to the ad window's end (frozen relative to spend)
    stale = (last_synced is None) or (str(last_synced)[:10] < cov_max)
    return {"has_ad": True, "cov_min": cov_min, "cov_max": cov_max,
            "total_spend": total_spend, "total_rev": total_rev,
            "account_tacos": account_tacos, "per_asin": per_asin,
            "last_synced": last_synced, "stale": stale}


# ─────────────────────────────────────────────────────────────────────────────
# PHASE C — day-parting schedule + action log
# ─────────────────────────────────────────────────────────────────────────────

def desired_state_for_hour(sched, hour):
    """'enabled' or 'paused' for a schedule row at a given hour (0-23). A 24-char
    hour_mask ('1'=on) overrides the simple [on_start_hour, on_end_hour) window;
    the window may wrap midnight (start > end)."""
    mask = (sched.get("hour_mask") or "").strip()
    if len(mask) == 24:
        return "enabled" if mask[hour] == "1" else "paused"
    s = int(sched.get("on_start_hour") or 0)
    e = int(sched.get("on_end_hour") if sched.get("on_end_hour") is not None else 24)
    if s <= e:
        on = (s <= hour < e)
    else:  # wraps midnight, e.g. 22:00 -> 06:00
        on = (hour >= s or hour < e)
    return "enabled" if on else "paused"


def upsert_schedule(account_id, campaign_id, campaign_name=None, active=None,
                    on_start_hour=None, on_end_hour=None, hour_mask=None, db_path=DB_PATH):
    """Create or update a campaign's schedule. Only non-None fields are changed."""
    conn = get_db(db_path)
    now = _now()
    existing = conn.execute(
        "SELECT * FROM ppc_campaign_schedule WHERE account_id=? AND campaign_id=?",
        (account_id, campaign_id)).fetchone()
    if existing:
        cur = dict(existing)
        vals = dict(
            campaign_name=campaign_name if campaign_name is not None else cur.get("campaign_name"),
            active=int(active) if active is not None else cur.get("active"),
            on_start_hour=int(on_start_hour) if on_start_hour is not None else cur.get("on_start_hour"),
            on_end_hour=int(on_end_hour) if on_end_hour is not None else cur.get("on_end_hour"),
            hour_mask=hour_mask if hour_mask is not None else cur.get("hour_mask"),
        )
        conn.execute("""UPDATE ppc_campaign_schedule SET campaign_name=?, active=?,
                        on_start_hour=?, on_end_hour=?, hour_mask=?, updated_at=?
                        WHERE account_id=? AND campaign_id=?""",
                     (vals["campaign_name"], vals["active"], vals["on_start_hour"],
                      vals["on_end_hour"], vals["hour_mask"], now, account_id, campaign_id))
    else:
        conn.execute("""INSERT INTO ppc_campaign_schedule
                        (account_id, campaign_id, campaign_name, active, on_start_hour,
                         on_end_hour, hour_mask, updated_at)
                        VALUES (?,?,?,?,?,?,?,?)""",
                     (account_id, campaign_id, campaign_name, int(active or 0),
                      int(on_start_hour if on_start_hour is not None else 0),
                      int(on_end_hour if on_end_hour is not None else 24), hour_mask, now))
    conn.commit()
    conn.close()


