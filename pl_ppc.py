def desired_state_for_hour(sched, hour):
    """'enabled' or 'paused' for a schedule row at a given hour (0-23). A 24-char
    hour_mask ('1'=on) overrides the simple [on_start_hour, on_end_hour) window;
    the window may wrap midnight (start > end)."""
    mask = (sched.get("hour_mask") or "").strip()
    if len(mask) == 24:
        return "enabled" if mask[hour] == "1" else "paused"
    s = int(sched.get("on_start_hour") or 0)
    e = int(sched.get("on_end_hour") if sched.get("on_end_hour") is not None else 24)
    if s <= e:
        on = (s <= hour < e)
    else:  # wraps midnight, e.g. 22:00 -> 06:00
        on = (hour >= s or hour < e)
    return "enabled" if on else "paused"


def _parse_iso(s):
    if not s:
        return None
    try:
        return datetime.fromisoformat(str(s))
    except Exception:
        return None


def is_snoozed(sched, now_dt=None):
    """True while a temporary pause is in effect (paused_until in the future)."""
    pu = _parse_iso(sched.get("paused_until"))
    if not pu:
        return False
    now_dt = now_dt or datetime.now(timezone.utc)
    if pu.tzinfo is None:
        pu = pu.replace(tzinfo=timezone.utc)
    if now_dt.tzinfo is None:
        now_dt = now_dt.replace(tzinfo=timezone.utc)
    return pu > now_dt


def desired_state_now(sched, now_hour, now_dt=None):
    """The state a campaign should be in RIGHT NOW. A temporary pause (snooze)
    overrides everything; otherwise the day-parting window if the schedule is active;
    otherwise 'enabled' — which is only ever applied to resume a snoozed campaign that
    isn't on the auto-schedule (a plain untracked campaign is never touched: see the
    reconciler, which skips rows that are neither active nor snoozed)."""
    if is_snoozed(sched, now_dt):
        return "paused"
    if sched.get("active"):
        return desired_state_for_hour(sched, now_hour)
    return "enabled"


def snooze_campaign(account_id, campaign_id, minutes, campaign_name=None, db_path=DB_PATH):
    """Temporarily pause a campaign for `minutes`, then auto-resume. Sets paused_until
    = now + minutes; creates the schedule row if the campaign isn't already tracked
    (active stays 0 — a snooze doesn't enrol it in day-parting). Returns paused_until."""
    until = (datetime.now(timezone.utc) + timedelta(minutes=int(minutes))).isoformat()
    conn = get_db(db_path)
    existing = conn.execute(
        "SELECT 1 FROM ppc_campaign_schedule WHERE account_id=? AND campaign_id=?",
        (account_id, campaign_id)).fetchone()
    if existing:
        conn.execute(
            "UPDATE ppc_campaign_schedule SET paused_until=?, "
            "campaign_name=COALESCE(?, campaign_name), updated_at=? "
            "WHERE account_id=? AND campaign_id=?",
            (until, campaign_name, _now(), account_id, campaign_id))
    else:
        conn.execute(
            "INSERT INTO ppc_campaign_schedule (account_id, campaign_id, campaign_name, "
            "active, on_start_hour, on_end_hour, hour_mask, paused_until, updated_at) "
            "VALUES (?,?,?,?,?,?,?,?,?)",
            (account_id, campaign_id, campaign_name, 0, 0, 24, None, until, _now()))
    conn.commit()
    conn.close()
    return until


