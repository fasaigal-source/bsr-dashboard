# TACOS — ad spend ÷ settlement-anchored total revenue (Module 2). Account-level
# headline + per-ASIN. NOT per-search-term (TACOS is undefined at term grain —
# the search-term table keeps ACOS). Two clocks: ad spend is click-date, revenue
# is settlement-date. Gated on sync freshness so it isn't divided into frozen revenue.
# ─────────────────────────────────────────────────────────────────────────────

def _asin_maps(conn):
    """Shared SKU→ASIN mapping (+ a representative ASIN→SKU for display), built from
    your SKU→ASIN table (cogs_sku_asin) and Amazon's advertised (asin, sku) pairs,
    normalised for the two real-data quirks (HTML entities like 18&quot;X4 vs 18"X4;
    alias/separator diffs via cogs_aliases). Returns
    (canon_to_asin, sku_to_asin, canon_fn, asin_to_sku)."""
    import html as _html
    alias_map = {r["variant_sku"]: r["canonical_sku"]
                 for r in conn.execute("SELECT variant_sku, canonical_sku FROM cogs_aliases").fetchall()}

    def _canon(s):
        s = s or ""
        if s in alias_map:
            return alias_map[s]
        u = _html.unescape(s)
        return alias_map.get(u, u)

    canon_to_asin, sku_to_asin, asin_to_sku = {}, {}, {}

    def _reg_sku(asin, sku):
        if not asin or not sku:
            return
        cur = asin_to_sku.get(asin)
        if cur is None or len(sku) < len(cur):   # shortest = most 'canonical-looking'
            asin_to_sku[asin] = sku

    for r in conn.execute("SELECT variant_sku, asin FROM cogs_sku_asin").fetchall():
        canon_to_asin.setdefault(_canon(r["variant_sku"]), r["asin"])
        sku_to_asin.setdefault(_html.unescape(r["variant_sku"] or ""), r["asin"])
        _reg_sku(r["asin"], r["variant_sku"])
    for r in conn.execute("SELECT DISTINCT asin, sku FROM ad_spend WHERE sku IS NOT NULL AND sku!=''").fetchall():
        canon_to_asin.setdefault(_canon(r["sku"]), r["asin"])
        sku_to_asin.setdefault(_html.unescape(r["sku"] or ""), r["asin"])
        _reg_sku(r["asin"], r["sku"])
    return canon_to_asin, sku_to_asin, _canon, asin_to_sku


def get_tacos(account_id="all", db_path=DB_PATH):
    import pl_ads
    conn = get_db(db_path)
    try:
        row = conn.execute("SELECT MAX(latest_synced) AS m FROM pl_sync_state").fetchone()
        last_synced = row["m"] if row and row["m"] else None
    except Exception:
        last_synced = None
    conn.close()

    cov_min, cov_max = pl_ads.get_ad_data_coverage(account_id=account_id, db_path=db_path)
    if not cov_min:
        return {"has_ad": False}

    ad_by_asin = pl_ads.get_ad_spend_by_asin(account_id, cov_min, cov_max, db_path=db_path)
    total_spend = round(sum((v.get("spend") or 0) for v in ad_by_asin.values()), 2)

    import html as _html
    conn = get_db(db_path)
    acc = " AND account_id=?" if (account_id and account_id != "all") else ""
    ap = [account_id] if acc else []
    # total settled gross (ex-VAT) over the ad-coverage window — the TACOS denominator
    total_rev = conn.execute(
        f"SELECT ROUND(SUM(sale_price_exvat),2) AS r FROM pl_line_items "
        f"WHERE substr(posted_date,1,10) >= ? AND substr(posted_date,1,10) <= ?{acc}",
        (cov_min, cov_max, *ap)).fetchone()["r"] or 0.0

    # Build SKU/canonical -> ASIN maps (+ ASIN -> representative SKU for display),
    # normalised for two real-data quirks so the per-ASIN revenue join actually hits:
    # (1) pl_line_items.sku stores HTML entities (e.g. 18&quot;X4) vs decoded 18"X4;
    # (2) separators/aliases differ (BD-6372=P4 vs BD-6372-P4). See _asin_maps.
    canon_to_asin, sku_to_asin, _canon, asin_to_sku = _asin_maps(conn)

    rev_by_asin = {}
    for r in conn.execute(
            f"""SELECT canonical_sku, sku, SUM(sale_price_exvat) AS rev FROM pl_line_items
                WHERE substr(posted_date,1,10) >= ? AND substr(posted_date,1,10) <= ?{acc}
                GROUP BY canonical_sku, sku""", (cov_min, cov_max, *ap)).fetchall():
        a = canon_to_asin.get(r["canonical_sku"]) or sku_to_asin.get(_html.unescape(r["sku"] or ""))
        if a:
            rev_by_asin[a] = rev_by_asin.get(a, 0.0) + (r["rev"] or 0.0)
    conn.close()

    per_asin = []
    for asin, v in ad_by_asin.items():
        rev = rev_by_asin.get(asin, 0.0)
        spend = round(v.get("spend") or 0, 2)
        per_asin.append({
            "asin": asin, "sku": asin_to_sku.get(asin), "spend": spend,
            "ad_sales": round(v.get("ad_sales") or 0, 2),
            "revenue": rev, "tacos": (spend / rev) if rev else None})
    per_asin.sort(key=lambda x: -(x["spend"] or 0))

    account_tacos = (total_spend / total_rev) if total_rev else None
    # stale = revenue hasn't caught up to the ad window's end (frozen relative to spend)
    stale = (last_synced is None) or (str(last_synced)[:10] < cov_max)
    return {"has_ad": True, "cov_min": cov_min, "cov_max": cov_max,
            "total_spend": total_spend, "total_rev": total_rev,
            "account_tacos": account_tacos, "per_asin": per_asin,
            "last_synced": last_synced, "stale": stale}


def get_campaign_tacos(account_id="all", db_path=DB_PATH):
    """Per-campaign TACOS = campaign ad spend (Search Term report, click-date) ÷
    settled ex-VAT revenue of the ASIN(s) that campaign advertises (settlement-date,
    Module 2). Because several campaigns can advertise the same SKU, they share that
    SKU's revenue — so per-campaign TACOS does NOT sum to the account figure. It
    answers 'this campaign's spend vs the revenue of the product it promotes'.
    Returns {'by_id': {campaign_id: {spend, ad_sales, orders, revenue, tacos, asins}},
    'dmin', 'dmax'}. Spend/revenue windowed to the imported Search Term date range."""
    import html as _html
    conn = get_db(db_path)
    w, p = _acct_where(account_id)
    dr = conn.execute(f"SELECT MIN(date) AS mn, MAX(date) AS mx FROM ppc_search_terms{w}", p).fetchone()
    dmin = dr["mn"] if dr else None
    dmax = dr["mx"] if dr else None
    if not dmin:
        conn.close()
        return {"by_id": {}, "dmin": None, "dmax": None}

    rows = conn.execute(f"""
        SELECT campaign_id, campaign_name, advertised_sku,
               ROUND(SUM(spend),2) AS spend, ROUND(SUM(sales),2) AS ad_sales, SUM(orders) AS orders
        FROM ppc_search_terms{w}
        GROUP BY campaign_id, campaign_name, advertised_sku
    """, p).fetchall()

    canon_to_asin, sku_to_asin, _canon, _ = _asin_maps(conn)
    acc = " AND account_id=?" if (account_id and account_id != "all") else ""
    ap = [account_id] if acc else []
    rev_by_asin = {}
    for r in conn.execute(
            f"""SELECT canonical_sku, sku, SUM(sale_price_exvat) AS rev FROM pl_line_items
                WHERE substr(posted_date,1,10) >= ? AND substr(posted_date,1,10) <= ?{acc}
                GROUP BY canonical_sku, sku""", (dmin, dmax, *ap)).fetchall():
        a = canon_to_asin.get(r["canonical_sku"]) or sku_to_asin.get(_html.unescape(r["sku"] or ""))
        if a:
            rev_by_asin[a] = rev_by_asin.get(a, 0.0) + (r["rev"] or 0.0)
    conn.close()

    camp = {}
    for r in rows:
        cid = r["campaign_id"]
        c = camp.setdefault(cid, {"campaign_id": cid, "campaign_name": r["campaign_name"],
                                  "spend": 0.0, "ad_sales": 0.0, "orders": 0, "asins": set()})
        c["spend"] += r["spend"] or 0
        c["ad_sales"] += r["ad_sales"] or 0
        c["orders"] += r["orders"] or 0
        a = (canon_to_asin.get(_canon(r["advertised_sku"]))
             or sku_to_asin.get(_html.unescape(r["advertised_sku"] or "")))
        if a:
            c["asins"].add(a)

    by_id = {}
    for cid, c in camp.items():
        rev = round(sum(rev_by_asin.get(a, 0.0) for a in c["asins"]), 2)
        by_id[cid] = {"campaign_id": cid, "campaign_name": c["campaign_name"],
                      "spend": round(c["spend"], 2), "ad_sales": round(c["ad_sales"], 2),
                      "orders": c["orders"], "revenue": rev,
                      "tacos": (c["spend"] / rev) if rev else None,
                      "asins": sorted(c["asins"])}
    return {"by_id": by_id, "dmin": dmin, "dmax": dmax}


# ─────────────────────────────────────────────────────────────────────────────
# PHASE A — recommendation worklist (dry-run, no creds, no writes to Amazon)
# Aggregates the Search Term report ACROSS hour+day rows to a per (campaign, ad
# group, target, search term) grain BEFORE applying rules — otherwise one term
# spread over 13 hourly 1-click rows reads as thirteen 1-click terms and every
# suggestion is wrong. Match-type branches the ACTION: manual keywords (EXACT/
# BROAD/PHRASE) → pause/bid the keyword; auto (TARGETING_EXPRESSION_PREDEFINED) →
# add a negative exact (needs only campaign/ad-group).
# ─────────────────────────────────────────────────────────────────────────────

_MANUAL_MATCH = {"BROAD", "EXACT", "PHRASE"}
# rule thresholds (tuned so the sample report yields 1 pause / 4 review / 60 harvest;
# reasonable general defaults too)
PAUSE_MIN_CLICKS = 8       # manual keyword, 0 sales, this many clicks → confident pause
REVIEW_MIN_CLICKS = 5      # 0 sales, sub-threshold spend, this many clicks → human look
REVIEW_MAX_SPEND = 5.0     # £ — below the "confident pause" spend, so route to review
HARVEST_MIN_ORDERS = 1     # non-manual (auto/product) term with ≥ this many orders → harvest
BID_DOWN_ACOS = 0.50       # converting manual keyword above this ACOS → suggest a lower bid
BID_DOWN_FACTOR = 0.75     # suggested new bid = current × this (a 25% trim)
BID_FLOOR = 0.05           # never suggest below this


def _is_manual(match_raw):
    return (match_raw or "").strip().upper() in _MANUAL_MATCH


def rebuild_recommendations(account_id, db_path=DB_PATH):
    """Regenerate the pending worklist for an account from the imported Search Term
    data. Returns a dict of bucket counts. DRY-RUN ONLY — writes recommendation rows,
    never touches Amazon. Existing NON-pending (decided) recs are preserved."""
    conn = get_db(db_path)
    conn.execute("DELETE FROM ppc_recommendations WHERE account_id=? AND status='pending'",
                 (account_id,))
    # aggregate across hour + day to the term×target grain
    rows = conn.execute("""
        SELECT campaign_id, MAX(campaign_name) AS campaign_name,
               ad_group_id, MAX(ad_group_name) AS ad_group_name,
               target_id, COALESCE(match_type_raw,'') AS match_raw,
               search_term, MAX(targeting_type) AS targeting_type,
               MAX(advertised_sku) AS sku, MAX(advertised_product_id) AS asin,
               MAX(target_bid) AS target_bid,
               SUM(impressions) AS impressions, SUM(clicks) AS clicks,
               ROUND(SUM(spend),2) AS spend, SUM(orders) AS orders, ROUND(SUM(sales),2) AS sales
        FROM ppc_search_terms
        WHERE account_id=?
        GROUP BY campaign_id, ad_group_id, target_id, COALESCE(match_type_raw,''), search_term
    """, (account_id,)).fetchall()

    now = _now()
    counts = {"pause": 0, "manual_review": 0, "harvest": 0, "bid_down": 0}
    harvest_terms = {}   # dedup harvest by search term (sum across its non-manual targets)

    def _add(rec_type, target, rationale, ev):
        conn.execute("""INSERT INTO ppc_recommendations
            (account_id, rec_type, target, rationale, evidence_json, status, created_at)
            VALUES (?,?,?,?,?, 'pending', ?)""",
            (account_id, rec_type, target, rationale, json.dumps(ev), now))
        counts[rec_type] = counts.get(rec_type, 0) + 1

    for r in rows:
        r = dict(r)
        manual = _is_manual(r["match_raw"])
        clicks, spend, orders, sales = (r["clicks"] or 0), (r["spend"] or 0), (r["orders"] or 0), (r["sales"] or 0)
        ev = {"campaign_id": r["campaign_id"], "campaign_name": r["campaign_name"],
              "ad_group_id": r["ad_group_id"], "ad_group_name": r["ad_group_name"],
              "target_id": r["target_id"], "match_type": r["match_raw"],
              "search_term": r["search_term"], "sku": r["sku"], "asin": r["asin"],
              "clicks": clicks, "spend": round(spend, 2), "orders": orders, "sales": round(sales, 2),
              "acos": (round(spend / sales, 3) if sales else None),
              "current_bid": r["target_bid"],
              "action_hint": "keyword_pause" if manual else "negative_exact"}

        # 1) PAUSE — manual keyword, real click volume, zero sales
        if manual and orders == 0 and clicks >= PAUSE_MIN_CLICKS:
            _add("pause", r["search_term"],
                 f"Manual {r['match_raw']} keyword, {clicks} clicks / £{spend:.2f}, 0 sales — pause it.", ev)
        # 2) MANUAL REVIEW — zero sales, some spend but below the confident-pause bar
        elif orders == 0 and spend < REVIEW_MAX_SPEND and clicks >= REVIEW_MIN_CLICKS:
            hint = "negative_exact" if not manual else "keyword_pause"
            ev["action_hint"] = hint
            _add("manual_review", r["search_term"],
                 f"{clicks} clicks / £{spend:.2f}, 0 sales ({'auto→negative' if not manual else r['match_raw']+' keyword'}) — review.", ev)
        # 3) BID DOWN — converting manual keyword, but ACOS too high
        elif manual and orders >= 1 and sales > 0 and r["target_bid"] and (spend / sales) > BID_DOWN_ACOS:
            new_bid = max(BID_FLOOR, round((r["target_bid"] or 0) * BID_DOWN_FACTOR, 2))
            ev["suggested_bid"] = new_bid
            _add("bid_down", r["search_term"],
                 f"{r['match_raw']} keyword converts but ACOS {100*spend/sales:.0f}% — "
                 f"cut bid £{r['target_bid']:.2f} → £{new_bid:.2f}.", ev)

        # HARVEST — non-manual (auto/product) converting term, deduped by search term
        if not manual and orders >= HARVEST_MIN_ORDERS:
            h = harvest_terms.setdefault(r["search_term"],
                {"clicks": 0, "spend": 0.0, "orders": 0, "sales": 0.0, "asin": r["asin"],
                 "campaign_id": r["campaign_id"], "campaign_name": r["campaign_name"],
                 "ad_group_id": r["ad_group_id"]})
            h["clicks"] += clicks; h["spend"] += spend; h["orders"] += orders; h["sales"] += sales

    for term, h in harvest_terms.items():
        ev = {"search_term": term, "clicks": h["clicks"], "spend": round(h["spend"], 2),
              "orders": h["orders"], "sales": round(h["sales"], 2),
              "acos": (round(h["spend"] / h["sales"], 3) if h["sales"] else None),
              "asin": h["asin"], "campaign_id": h["campaign_id"],
              "campaign_name": h["campaign_name"], "ad_group_id": h["ad_group_id"],
              "action_hint": "harvest_exact"}
        _add("harvest", term,
             f"Converting term ({h['orders']} order(s) / £{h['sales']:.2f}) from auto/product "
             f"targeting — add as its own exact keyword.", ev)

    conn.commit()
    conn.close()
    log.info("PPC recommendations rebuilt (%s): %s", account_id, counts)
    return counts


